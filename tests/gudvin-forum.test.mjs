import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import {parseForumCSV} from '../scripts/forum-directory.mjs';
import {normalizeData} from '../js/data.js';
import {buildForumLink,selectForumRows} from '../js/forum-link-model.js';
import {unifiedAt} from '../js/calculations.js';
const id='f266d10e-1f69-471e-ab35-65e5f5a30c0a';
const read=name=>JSON.parse(fs.readFileSync('data/'+name));
test('GudVin GK has one confirmed forum identity, correct grades, and belongs to the Forum TUZ selection',()=>{
 const rows=parseForumCSV(fs.readFileSync('data/forum.csv','utf8'));
 const normalized=s=>s.normalize('NFKC').replace(/\s+/gu,'').toLocaleLowerCase('ru-RU');
 assert.equal(new Set(rows.map(r=>r.userId)).size,rows.length);
 assert.equal(new Set(rows.map(r=>normalized(r.forum_name))).size,rows.length);
 assert.deepEqual(rows.filter(r=>r.userId===id),[{group:'OG',forum_name:'ГудВин [ГК]',userId:id}]);
 const main=read('19ib_all_judges_REPAIRED.json'),forum=read('forum_judges_export.json'),D=normalizeData(main,forum);
 const person=D.byId.get(id),meta=D.metadata.get(id);
 assert.equal(person.artistName,'ГудВин [ГК]');assert.equal(person.artistSlug,'gudvin-gk');
 assert.deepEqual(person.scores.map(s=>s.score).sort(),[4,4,4,5,5]);
 assert.equal(meta.group,'OG');assert.equal(meta.veteran,false);assert.deepEqual(meta.scores,person.scores);
 const model=buildForumLink(D),matches=selectForumRows(model.forum,{query:'гудвин [гк]',group:'current'});
 assert.deepEqual(matches.map(p=>p.id),[id]);assert.equal(matches[0].total,22);
 assert.equal(matches[0].battleProfile,'https://19ib.ru/artist/gudvin-gk');
 assert(!model.other.some(p=>p.id===id));assert(!model.veterans.some(p=>p.id===id));
 const group=new Set(forum.members.filter(p=>D.byId.has(p.userId)&&p.group!=='Ветераны'&&!p.veteran).map(p=>p.userId));
 assert(group.has(id));
 const events=D.events.map(s=>({...s,forum:group.has(s.userId)}));
 assert.equal(events.filter(s=>s.userId===id&&s.forum).length,5);
 const index=unifiedAt(events,group.size,5,Date.parse(main.exportedAt),{otherCount:main.members.length-group.size,historical:false}).index;
 const history=read('history.json'),last=history.snapshots.at(-1);
 assert.equal(last.indices.forum.index,index);
 const selection=history.selectionVersions.find(v=>v.id===last.selectionVersion);
 assert(selection.directory.some(p=>p.userId===id&&p.group==='OG'));
});
